export const LANGS = ['en', 'ceb', 'tl'];

let current = 'en';

export function setLang(code) {
  current = STRINGS[code] ? code : 'en';
  document.documentElement.lang = current === 'ceb' ? 'ceb'
                                : current === 'tl'  ? 'fil'
                                : 'en';
  return current;
}

export function getLang() { return current; }

export function t(key) {
  return STRINGS[current][key] ?? STRINGS.en[key] ?? key;
}

/** English is the only language here that pluralises the noun. */
export function glassWord(n) {
  if (current !== 'en') return t('fluid.glassesLeft');
  return n === 1 ? 'glass left for today' : 'glasses left for today';
}

export function langName(code) { return STRINGS[code]['lang.name']; }
